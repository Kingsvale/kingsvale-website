test("client address resolver rejects spoofed forwarding and normalizes IPv4/IPv6", () => {
  const request = (peer, headers) => ({ socket: { remoteAddress: peer }, headers });
  assert.equal(normalizeIp("::ffff:192.0.2.1"), "192.0.2.1");
  assert.equal(normalizeIp("2001:0db8:0000:1::5"), "2001:db8:0:1::5");
  assert.equal(networkAddress("2001:db8:1:2:3:4:5:6"), "2001:db8:1:2::/64");
  assert.equal(normalizeIp("1.2.3.4, 2.3.4.5"), null);
  const direct = resolveClientAddress(request("192.0.2.1", { "x-forwarded-for": "198.51.100.9" }), {});
  assert.equal(direct.ip, "192.0.2.1"); assert.equal(direct.reliable, false);
  const trusted = { TRUSTED_PROXY_CIDRS: "10.0.0.0/8" };
  assert.equal(resolveClientAddress(request("10.1.1.1", { "x-forwarded-for": "198.51.100.8, 192.0.2.5, 10.1.1.2" }), trusted).ip, "192.0.2.5");
  assert.equal(resolveClientAddress(request("10.1.1.1", { "x-forwarded-for": "not-an-ip" }), trusted).reliable, false);
  assert.equal(resolveClientAddress(request("10.1.1.1", { "cf-connecting-ip": "192.0.2.7" }), { ...trusted, CLIENT_IP_HEADER: "cf-connecting-ip" }).ip, "192.0.2.7");
});

